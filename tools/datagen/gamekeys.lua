-- Locales/Game.lua: each key the enUS locale files mark [game: TAG] (localenotes.lua) with its tag,
-- for ns.GameText in Core.lua, which reads those strings from the running game in the player's
-- language. Only GlobalStrings tags: a "Table.ID" one (CreatureType.1) isn't a global of the
-- client's, so a language keeps its own copy of those. It reads no table, only our own files, but
-- it's written here with tests/data/GameText.lua so the two can't disagree.
local Lua = require("luaout")
local Notes = require("localenotes")

local M = {
    path = "ForeverPlusPlus/Locales/Game.lua",
    tables = {},
}

-- For summary.lua: a key's line.
function M.Entry(line)
    local key = line:match("^    ([%w_]+) = ")
    if key then
        return key, line
    end
end

local function readFile(path)
    local file = assert(io.open(path, "rb"), "can't read " .. path)
    local text = file:read("*a")
    file:close()
    return text
end

function M.Build(_, _, script, root)
    local list = {}
    for line in readFile(root .. "/ForeverPlusPlus/ForeverPlusPlus.toc"):gmatch("[^\r\n]+") do
        local name = line:match("^Locales[/\\]enUS[/\\](.+%.lua)$")
        if name then
            local path = root .. "/ForeverPlusPlus/Locales/enUS/" .. name
            local entries, problem = Notes.Read(readFile(path))
            if problem then
                error(path .. ": " .. problem)
            end
            for _, entry in ipairs(entries) do
                if entry.game and not entry.game:find(".", 1, true) then
                    list[#list + 1] = entry
                end
            end
        end
    end
    table.sort(list, function(a, b)
        return a.key < b.key
    end)

    local out = {
        "-- The strings that are the game's own wording, each with the name of the client's global string",
        "-- for it: ns.GameText (Core.lua) reads them from the game in the player's language, so no",
        "-- language file has to carry them. From the [game: TAG] notes in Locales/enUS/.",
        "--",
        "-- Generated by " .. script .. ". Don't edit it by hand: add or change the note in",
        "-- the enUS file and run the script again.",
        "local _, ns = ...",
        "",
        "ns.GameText({",
    }
    for _, entry in ipairs(list) do
        out[#out + 1] = ("    %s = %s,"):format(entry.key, Lua.String(entry.game))
    end
    out[#out + 1] = "})"
    return table.concat(out, "\n") .. "\n"
end

return M
